"""Benchmark the hosted-API system <SYSTEM> on TabArena-v0.1: `audit`, `smoke`, `setup`, `eval`.

ONE file, the API counterpart of ``run_benchmark_template.py``. The shared identity (``BENCHMARK_NAME``,
``WORKSPACE``, ``PYTHON_PATH``, ``SYSTEM``) is defined once at the top::

    <PYTHON_PATH> -P tmp_scripts/run_<system>.py audit --offline  # what the client sends; no key, nothing sent
    <PYTHON_PATH> -P tmp_scripts/run_<system>.py audit            # cheating probes against the API (key needed)
    <PYTHON_PATH> -P tmp_scripts/run_<system>.py smoke            # official pipeline on three small tasks, here
    <PYTHON_PATH> -P tmp_scripts/run_<system>.py setup            # job JSON + the one sbatch command
    <PYTHON_PATH> -P tmp_scripts/run_<system>.py eval             # leaderboards + all figures

The key never goes into this file or the job JSON: export ``<KEY_ENV>`` in the shell that runs ``audit``,
``smoke`` and the ``sbatch`` command (the job inherits the submitting shell's environment,
``--export=ALL``). ``setup`` itself needs no key.

``setup --scheduler single-node`` (default) runs every item from one on-demand CPU node with
``NUM_WORKERS`` requests in flight; ``--scheduler array`` spreads the items over an array of CPU nodes
(``NUM_WORKERS`` concurrent array tasks). Either way the provider sees at most ``NUM_WORKERS``
concurrent requests.

With ``SUBMITTED_RESULTS`` set (the submitter's own TabArena-Lite ``per_split.csv``, one per config),
``audit`` compares the submission with the hosted methods, and ``smoke`` and ``eval`` compare our run with
the submission on the splits both cover (``compare_reproduced_results``): the three smoke splits first,
all of TabArena-Lite after the full run. Only CSVs from a submitter are read, never their pickles.

Generated by the ``benchmark-model`` skill; lives under ``tmp_scripts/`` (gitignored) on purpose.

<SYSTEM> notes:
- Endpoint and key: <URL env var / default URL>, key in <KEY_ENV>.
- Configs: <the generator's manual configs, e.g. preset=medium (c1), preset=full (c2)>
- Concurrency agreed with the provider: <N>; provider hardware: <e.g. one A100 80 GB per fit>.
- Timing: <"fit and predict in one call: the whole fit lands in time_infer_s" | "separate fit/predict calls">
- <any per-run gotcha>
"""

from __future__ import annotations

import argparse
import json
import os
import sys
from dataclasses import asdict
from pathlib import Path

import pandas as pd

from tabarena.benchmark.experiment import TabArenaV0pt1ExperimentBundle
from tabarena.benchmark.task.metadata import TaskSubset
from tabarena.evaluation import EvalMethod, TabArenaEvalConfig, run_eval
from tabflow_slurm import (
    GCPSlurmSetup,
    ModelJob,
    PathSetup,
    SlurmSingleNodeSetup,
    TabArenaV0pt1BenchmarkPlan,
    TabArenaV0pt1ResourcesSetup,
)

REPO_ROOT = Path(__file__).resolve().parents[1]  # tmp_scripts/ sits at the repo root
OUT = Path(__file__).parent / "eval_output"

# ── Shared identity: the ONE place these live ──
BENCHMARK_NAME = "<system>_<DDMMYYYY>"  # cache key; reused unchanged across relaunches
WORKSPACE = "/home/lennart_priorlabs_ai/workspace/benchmarking/tabarena_workspace"
PYTHON_PATH = "<PYTHON_PATH>"  # the venv whose `tabarena` imports THIS checkout (the skill resolves it)

SYSTEM = "<System>"  # registry name in tabarena.systems
KEY_ENV = "<KEY_ENV>"  # the environment variable the wrapper reads its key from
NUM_WORKERS = 4  # EDIT: concurrent requests the provider allows
PARTITION = "cpuhighmem16"  # on-demand (not spot) 8-core / 122 GB node; the client needs no GPU
TIME_LIMIT = 3600  # seconds per item, forwarded to the API as its fit budget (TabArena-v0.1 default)

SMOKE_DATASETS = ["blood-transfusion-service-center", "maternal_health_risk", "QSAR_fish_toxicity"]
SMOKE_TIME_LIMIT = 300
# EDIT: the submitter's self-reported per-split CSV (dataset, fold, metric_error) for each config,
# e.g. {"<Name>_c1_default": "<dir>/per_split_medium.csv"}; a CSV holding several configs is filtered by name.
SUBMITTED_RESULTS: dict[str, str] = {}


def _info():
    from tabarena.systems import get_system_registry

    return get_system_registry()[SYSTEM]


def _path_setup() -> PathSetup:
    return PathSetup(workspace=WORKSPACE, python_path=PYTHON_PATH)


def _require_key() -> None:
    if not os.environ.get(KEY_ENV):
        sys.exit(f"Export {KEY_ENV} in this shell first (it is read at call time and never stored).")


def audit(*, offline: bool = False, **_) -> None:
    """Client scan + outbound requests (``--offline``: network blocked), or the full cheating probes."""
    from tabarena.tools.audit_system import main as audit_main

    argv = ["--system", SYSTEM, "--json", str(OUT / BENCHMARK_NAME / f"audit_{'offline' if offline else 'live'}.json")]
    if offline:
        # The wrapper may read the key before it builds the request; the request is refused either way.
        os.environ.setdefault(KEY_ENV, "offline-audit-placeholder")
        argv.append("--offline")
    else:
        _require_key()
        if SUBMITTED_RESULTS:
            argv += ["--submitted-results", *dict.fromkeys(SUBMITTED_RESULTS.values())]
    sys.exit(audit_main(argv))


def _submitted(config: str) -> pd.DataFrame:
    frame = pd.read_csv(SUBMITTED_RESULTS[config])
    if "method" in frame and len(set(frame["method"])) > 1:
        frame = frame[frame["method"].astype(str).str.contains(config, regex=False)]
    return frame


def _check_reproduction(ours: pd.DataFrame, stage: str) -> None:
    """Our errors against the submitter's self-reported ones, per config, on the splits both cover."""
    from tabarena.tools.audit_system import compare_reproduced_results, format_result

    results = [
        compare_reproduced_results(ours[ours["method"] == config], _submitted(config), label=config)
        for config in SUBMITTED_RESULTS
    ]
    for result in results:
        print(f"{stage} {format_result(result)}")
    if results:
        path = OUT / BENCHMARK_NAME / f"reproduction_{stage.lower()}.json"
        path.write_text(json.dumps([asdict(r) for r in results], indent=2, default=str))
        print(f"{stage} reproduction details: {path}")


def smoke(**_) -> None:
    """Every config on the first split of three small tasks, through the official pipeline, in this process."""
    from tabarena.contexts import TabArenaContext

    _require_key()
    experiments = TabArenaV0pt1ExperimentBundle(
        models=[(_info().config_generator, 0)],
        system_experiments=True,
    ).build_experiments(time_limit=SMOKE_TIME_LIMIT)
    results = TabArenaContext().build_and_run_jobs(
        experiments,
        expname=str(OUT / BENCHMARK_NAME / "smoke"),
        task_subset=TaskSubset(subset="lite", dataset_names=SMOKE_DATASETS),
        register=False,
        debug_mode=True,
    )
    for r in results:
        print(
            f"SMOKE {r['framework']:<28} {r['task_metadata']['name']:<34} error {r['metric_error']:.4f} "
            f"train {r['time_train_s']:.1f}s infer {r['time_infer_s']:.1f}s",
        )
    expected = len(experiments) * len(SMOKE_DATASETS)
    print(f"SMOKE {'OK' if len(results) == expected else 'INCOMPLETE'}: {len(results)}/{expected} items.")
    from tabarena.tools.audit_system import results_frame

    _check_reproduction(results_frame(results), "SMOKE")


def _scheduler(kind: str):
    if kind == "single-node":
        return SlurmSingleNodeSetup(partition=PARTITION, num_workers=NUM_WORKERS)
    # Many nodes, each one item at a time; the array's %N is the provider's concurrency.
    return GCPSlurmSetup(
        cpu_partition=PARTITION,
        bundle_size=10,
        array_job_limit=NUM_WORKERS,
        setup_ray_for_slurm_shared_resources_environment=False,
    )


def setup(scheduler: str = "single-node", **_) -> None:
    """Write the job files for every config on the full task set and print the launch command."""
    plan = TabArenaV0pt1BenchmarkPlan(
        benchmark_name=BENCHMARK_NAME,
        model_jobs=[
            ModelJob(models=(_info().config_generator, 0), name="api", resources={"time_limit": TIME_LIMIT}),
        ],
        task_subset=TaskSubset(),  # the full task set (all splits)
        path_setup=_path_setup(),
        experiment_bundle=TabArenaV0pt1ExperimentBundle(model_verbosity=2, system_experiments=True),
        resources_setup=TabArenaV0pt1ResourcesSetup(num_cpus=None, memory_limit=None),
        scheduler_setup=_scheduler(scheduler),
        prefetch_model_weights=False,  # nothing local to prefetch for an API
    )
    plan.setup_jobs()
    print(f"Export {KEY_ENV} in the shell that runs the sbatch command.")


def evaluate(**_) -> None:
    """Leaderboards and figures, one labelled entry per config of the system, then the reproduction check."""
    info = _info()
    name = info.config_generator.name
    methods = [
        EvalMethod(
            SYSTEM,
            ag_name_override=f"{name}_c{i}",
            display_name_override=f"{info.method_metadata.display_name} ({cfg.get('preset', f'c{i}')})",
        )
        for i, cfg in enumerate(info.config_generator.manual_configs, start=1)
    ]
    config = TabArenaEvalConfig(
        benchmark_name=BENCHMARK_NAME,
        output_dir=_path_setup().get_output_path(BENCHMARK_NAME),
        methods=methods,
        figure_output_dir=OUT / BENCHMARK_NAME,
        subsets=[[], ["binary"], ["multiclass"], ["regression"]],
        figure_file_type=("pdf", "png"),
        pareto_focus_new_methods=True,
    )
    leaderboards = run_eval(config)
    for label, leaderboard in leaderboards.items():
        ranked = leaderboard.sort_values("elo", ascending=False).reset_index(drop=True)
        for pos, row in ranked[ranked.get("ta_suite") == BENCHMARK_NAME].iterrows():
            print(f"[{label}] #{pos + 1}/{len(ranked)}  {row['method']}  Elo {row['elo']:.0f}")
    if SUBMITTED_RESULTS:
        from tabarena.tools.audit_system import load_results_frame

        _check_reproduction(load_results_frame(Path(_path_setup().get_output_path(BENCHMARK_NAME)) / "data"), "EVAL")


MODES = {"audit": audit, "smoke": smoke, "setup": setup, "eval": evaluate}

if __name__ == "__main__":
    parser = argparse.ArgumentParser(description="Run the audit, smoke, setup or eval part of this benchmark.")
    parser.add_argument("mode", choices=list(MODES))
    parser.add_argument("--offline", action="store_true", help="audit: block the network, read the client only.")
    parser.add_argument("--scheduler", choices=("single-node", "array"), default="single-node")
    args = parser.parse_args()
    MODES[args.mode](offline=args.offline, scheduler=args.scheduler)

"""Benchmark <MODEL> on TabArena-v0.1: `smoke` (local fit), `setup` (cluster launch), `eval` (leaderboard).

ONE file, THREE subcommands. `setup` and `eval` share the same ``BENCHMARK_NAME`` and
``PathSetup`` (``WORKSPACE`` + ``PYTHON_PATH``) defined once at the top, so the launch
and the evaluation can never drift apart::

    <PYTHON_PATH> tmp_scripts/run_<model>.py smoke   # fit the model on AutoGluon's toy datasets, locally
    <PYTHON_PATH> tmp_scripts/run_<model>.py setup   # generate the job JSON + emit the sbatch command(s)
    <PYTHON_PATH> tmp_scripts/run_<model>.py eval    # leaderboards + all figures for the default subsets

``--scheduler skypilot`` / ``skypilot-pool`` runs the same plan as SkyPilot managed jobs instead of
SLURM (prerequisites: the cluster's ``sky`` CLI on PATH with ``SKYPILOT_API_SERVER_ENDPOINT`` set
(login nodes preset it), ``sky check gcp``, and ``HF_TOKEN`` in the shell for gated weights); ``eval``
then syncs the bucket's results into the workspace first.

Generated by the ``benchmark-model`` skill; lives under ``tmp_scripts/`` (gitignored) on purpose.

<MODEL> notes:
- Extra deps (the skill installs them into the run venv): <PIP_EXTRA or "none">
- Problem types: <PROBLEM_TYPES>  (drives the eval ``subsets`` below)
- Foundation-model weights: <"prefetched from HF by the registry" if prefetch_weights else "none">
- Configs: <"all" = default config + the full HPO search space | 0 = default config only, no search space>
- <any per-run gotcha: partition choice, per-dataset time-limit bumps, fake VRAM, ...>
"""

from __future__ import annotations

import argparse
import sys
from pathlib import Path
from typing import TYPE_CHECKING

from tabarena.benchmark.experiment import TabArenaV0pt1ExperimentBundle
from tabarena.benchmark.task.metadata import TaskSubset
from tabarena.evaluation import EvalMethod, TabArenaEvalConfig, run_eval
from tabflow_slurm import (
    GCPSlurmSetup,
    ModelJob,
    PathSetup,
    SchedulerSetup,
    SkyPilotSetup,
    TabArenaV0pt1BenchmarkPlan,
    TabArenaV0pt1ResourcesSetup,
)

if TYPE_CHECKING:
    import pandas as pd

REPO_ROOT = Path(__file__).resolve().parents[1]  # tmp_scripts/ sits at the repo root

# ── Shared identity: the ONE place these live; smoke, setup and eval all read them ──
BENCHMARK_NAME = "<model>_<DDMMYYYY>"  # cache key; reused unchanged across reruns
WORKSPACE = "/home/lennart_priorlabs_ai/workspace/benchmarking/tabarena_workspace"
PYTHON_PATH = "<PYTHON_PATH>"  # the venv whose `tabarena` imports THIS checkout (the skill resolves it)

MODEL = "<Model>"  # registry name, e.g. "TabM" / "Nori" / "DenseLight"
NUM_CONFIGS = "all"  # "all" = default config + the full HPO space; 0 = default only (foundation models)

# Hyperparameters added on top of the registry smoke config for the local `smoke` fit, e.g.
# {"device": "cpu"} for a wrapper that reads a `device` hyperparameter and must be told when the
# machine has no CUDA device. Leave empty when the wrapper picks its device from `num_gpus`.
SMOKE_EXTRA_HYPERPARAMETERS: dict = {}

SCHEDULERS = ("slurm", "skypilot", "skypilot-pool")


def _path_setup() -> PathSetup:
    return PathSetup(workspace=WORKSPACE, python_path=PYTHON_PATH)


def _scheduler_setup(kind: str) -> tuple[SchedulerSetup, int]:
    """The scheduler for ``kind`` and the VRAM in GB of the GPU its jobs land on.

    The VRAM feeds ``fake_memory_for_estimates`` (GPU models only); both schedulers land on an
    RTX PRO 6000 (96 GB) by default. GPU: bundle_size=1 (one fit per task) and workers=32, about what
    the GPU partition sustains. CPU model: GCPSlurmSetup(cpu_partition="cpun416mtspotinteractive",
    bundle_size=2), the 16 vCPU / 64 GB partition the CPU tree boosters were timed on, and
    SkyPilotSetup(bundle_size=10, workers=100) (its CPU default is the same 16 vCPU / 64 GB shape; a
    200-config sweep has ~160k items, so a bigger bundle keeps the queue listable and workers is the
    concurrency you want to pay for).
    """
    if kind == "slurm":
        return GCPSlurmSetup(gpu_partition="gpurtxpro6000flex", bundle_size=1), 96  # RTX PRO 6000
    sky = SkyPilotSetup(
        bundle_size=1,
        workers=32,  # concurrent worker jobs (and the pool size); SLURM's %N analogue
        secrets=("HF_TOKEN",),  # EDIT: drop for models whose weights are not gated
        use_pool=kind == "skypilot-pool",
    )
    return sky, 96


def smoke(_scheduler: str = "slurm") -> None:
    """Fit ``MODEL`` on AutoGluon's toy datasets on this machine.

    The body of ``tests/tabarena/models/test_all_models.py`` without its GPU skip: the same toy
    hyperparameters from ``smoke_configs.py`` and the same ``FitHelper.verify_model`` call. A GPU
    model is fit on the CPU when no CUDA device is available, so the wrapper's import, fit,
    predict and save/load paths are exercised before any cluster time is spent.
    """
    import importlib.util

    from tabarena.models import get_model_registry

    sys.path.insert(0, str(REPO_ROOT))
    from tests.tabarena.models.smoke_configs import smoke_for

    info = get_model_registry()[MODEL]
    if info.superseded:
        print(
            f"WARNING: {MODEL} is superseded; its pip_extra {info.pip_extra} may conflict with the installed version."
        )
    has_cuda = False
    if importlib.util.find_spec("torch") is not None:
        import torch

        has_cuda = torch.cuda.is_available()
    if info.method_metadata.compute == "gpu" and not has_cuda:
        print(f"{MODEL} is a GPU model and no CUDA device is available here: fitting on the CPU.")

    from autogluon.tabular.testing import FitHelper

    cfg = smoke_for(MODEL)
    kwargs: dict = {
        "model_cls": info.model_cls,
        "model_hyperparameters": {**cfg.hyperparameters, **SMOKE_EXTRA_HYPERPARAMETERS},
    }
    if cfg.problem_types is not None:
        kwargs["problem_types"] = list(cfg.problem_types)
    if not cfg.verify_single_prediction_equivalent_to_multi:
        kwargs["verify_single_prediction_equivalent_to_multi"] = False
    FitHelper.verify_model(**kwargs)
    print(f"SMOKE OK: {MODEL} fit, predicted and reloaded on the {'GPU' if has_cuda else 'CPU'}.")


def setup(scheduler: str = "slurm") -> None:
    """Generate the job files and emit the launch command(s) for ``scheduler``."""
    # TabArenaV0pt1BenchmarkPlan pre-wires the v0.1 defaults (TabArenaContext,
    # TabArenaV0pt1ExperimentBundle, GCPSlurmSetup, TabArenaV0pt1ResourcesSetup);
    # the explicit fields below are deliberate overrides on those defaults.
    scheduler_setup, vram_gb = _scheduler_setup(scheduler)
    plan = TabArenaV0pt1BenchmarkPlan(
        benchmark_name=BENCHMARK_NAME,
        model_jobs=[
            ModelJob(
                models=(MODEL, NUM_CONFIGS),
                name="gpu",  # CPU model: use name="cpu" and drop the resources dict below
                resources={
                    "num_gpus": 1,
                    # REQUIRED for every GPU model: the VRAM in GB of the card the scheduler lands on
                    # (from _scheduler_setup: RTX PRO 6000 -> 96 on both schedulers by default).
                    # AutoGluon budgets parallel bagging folds against this memory figure;
                    # without it folds are budgeted by node RAM and can OOM the GPU.
                    "fake_memory_for_estimates": vram_gb,
                },
                # Long tail? add "time_limit": <seconds> to the resources dict above.
            ),
        ],
        task_subset=TaskSubset(),  # the full task set (all splits); TaskSubset(subset="lite") for a first-split trial
        path_setup=_path_setup(),
        # model_verbosity=2 quiets every model's fit log (the bundle default is 4 with CatBoost at 2).
        experiment_bundle=TabArenaV0pt1ExperimentBundle(model_verbosity=2),
        # num_cpus=None resolves to the node's CPU affinity count at run time (24 on gpurtxpro6000flex),
        # which is what the runner's CPU consistency check expects on an exclusive node.
        resources_setup=TabArenaV0pt1ResourcesSetup(num_cpus=None, memory_limit=None),
        scheduler_setup=scheduler_setup,
    )
    plan.setup_jobs()


def evaluate(scheduler: str = "slurm") -> None:
    """Build the TabArena-v0.1 leaderboards and every figure for the default subsets."""
    # SkyPilot workers write into the bucket; bring their results into the workspace first (no-op for SLURM).
    _scheduler_setup(scheduler)[0].sync_results_to_local(
        path_setup=_path_setup(), benchmark_name=BENCHMARK_NAME, force=True
    )
    config = TabArenaEvalConfig(
        benchmark_name=BENCHMARK_NAME,
        output_dir=_path_setup().get_output_path(BENCHMARK_NAME),
        # Labelled with the registry's display_name in the leaderboard and figures; add result_suffix
        # (re-run of a hosted model), only_load_cache or display_name_override if needed.
        methods=[EvalMethod(MODEL)],
        figure_output_dir=Path(__file__).parent / "eval_output" / BENCHMARK_NAME,
        # `[]` = the full task set (overall leaderboard), then one view per problem type.
        # Regression-only model: [["regression"]]. Classification-only: drop ["regression"].
        subsets=[[], ["binary"], ["multiclass"], ["regression"]],
        figure_file_type=("pdf", "png"),  # PNGs render inline, PDFs are for papers
        pareto_focus_new_methods=True,  # box-label MODEL in every Pareto figure, not only when it is on the front
    )
    leaderboards = run_eval(config)
    _print_new_method_positions(leaderboards)


def _print_new_method_positions(leaderboards: dict[str, pd.DataFrame]) -> None:
    """Print where the run's methods landed in each subset's leaderboard, in Elo order."""
    print("\n##### Position of this run's methods (Elo order)")
    for label, leaderboard in leaderboards.items():
        if "ta_suite" not in leaderboard.columns:
            continue
        ranked = leaderboard.sort_values("elo", ascending=False).reset_index(drop=True)
        for pos, row in ranked[ranked["ta_suite"] == BENCHMARK_NAME].iterrows():
            imputed = f", {100 * row['imputed']:.1f}% imputed" if row.get("imputed", 0) else ""
            print(
                f"[{label}] #{pos + 1}/{len(ranked)}  {row['method']}  "
                f"Elo {row['elo']:.0f} (+{row['elo+']:.0f}/-{row['elo-']:.0f}){imputed}",
            )


MODES = {"smoke": smoke, "setup": setup, "eval": evaluate}
DEFAULT_MODE = "setup"  # bare invocation (no mode arg) runs this

if __name__ == "__main__":
    parser = argparse.ArgumentParser(description="Run the smoke, setup or eval part of this benchmark.")
    parser.add_argument("mode", nargs="?", default=DEFAULT_MODE, choices=list(MODES))
    parser.add_argument(
        "--scheduler",
        choices=SCHEDULERS,
        default="slurm",
        help="Where the jobs run: the GCP SLURM cluster (default), SkyPilot managed jobs on their own spot VMs, "
        "or a SkyPilot job pool.",
    )
    args = parser.parse_args()
    MODES[args.mode](args.scheduler)
